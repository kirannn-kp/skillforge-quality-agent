import { expect, test } from '@playwright/test';

test('proactive detection requires approval, then links persistent incident evidence to the live station alert', async ({ page, context }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/api/health', async route => {
    const response = await route.fetch();
    const health = await response.json();
    await route.fulfill({ response, json: { ...health, conversation: { configured: true, model: 'synthetic-dialogue-test' } } });
  });
  await page.goto('/?workspace=quality&scoutTheme=dark');
  await expect(page.getByRole('heading', { name: 'Quality Early-Warning Control Tower' })).toBeVisible();
  await expect(page.getByRole('region', { name: 'Fleet monitoring summary' })).toContainText('1,000');
  await expect(page.getByText('DEMO-00427 / Station 42', { exact: true })).toBeVisible();
  await page.getByLabel('Search vehicle ID or station').fill('DEMO-00427');
  await page.getByRole('button', { name: 'Search records', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'DEMO-00427', exact: true })).toBeVisible();

  const station = await context.newPage();
  await station.goto('/?workspace=quality&station=Station%2042&scoutTheme=dark');
  await expect(station.getByRole('heading', { name: 'No approved incident alerts' })).toBeVisible();
  await page.getByRole('button', { name: 'Open investigation', exact: true }).click();
  await expect(page).toHaveURL('/?scoutTheme=dark');
  const live = page;
  await expect(live.getByRole('heading', { name: 'Human approval required' })).toBeVisible({ timeout: 15000 });
  await expect(live.locator('.assistant-response')).toContainText('Would you like me to create an incident');
  await expect(live.getByRole('tab', { name: 'Investigation', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(live.locator('.photo-frame img')).toHaveAttribute('src', '/reference-images/door-hinge.png');
  await expect(live.getByRole('link', { name: /^Open INC-.* details$/ })).toHaveCount(0);
  expect(await (await page.request.get('/api/incidents')).json()).toHaveLength(0);
  await expect(station.getByRole('heading', { name: 'No approved incident alerts' })).toBeVisible();
  await live.getByRole('button', { name: /Open conversation & checklist/ }).click();
  await live.getByLabel('Operator message').fill('Can you tell me your investigation?');
  await live.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(live.getByRole('log')).toContainText('62 N against a 50 N');
  await live.getByLabel('Operator message').fill('Can you create an incident, alert Station 42 and save these findings?');
  await live.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(live.locator('.assistant-response')).toContainText('Shall I go ahead?');
  await expect(live.locator('.assistant-response')).not.toContainText('62 N');
  await expect(live.getByRole('tab', { name: 'Incident', exact: true })).toHaveAttribute('aria-selected', 'true');
  expect(await (await page.request.get('/api/incidents')).json()).toHaveLength(0);
  await live.getByLabel('Operator message').fill('Yes, please create the incident and send the alert.');
  await live.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(live.getByRole('log')).toContainText('What else would you like me to investigate?');
  await expect(live.getByRole('tab', { name: 'Incident', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(live.getByLabel('Operator message')).toBeEnabled();
  await live.getByLabel('Operator message').fill('Tell me your findings.');
  await live.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(live.getByRole('log')).toContainText('already saved');
  await expect(live.getByRole('tab', { name: 'Investigation', exact: true })).toHaveAttribute('aria-selected', 'true');
  expect(await (await page.request.get('/api/incidents')).json()).toHaveLength(1);
  await live.getByRole('button', { name: 'Close drawer', exact: true }).click();
  await live.getByRole('tab', { name: 'Incident', exact: true }).click();
  await expect(live.getByText(/Incident created\. Sent alert to Station 42/)).toBeVisible();
  const detailLink = live.getByRole('link', { name: /^Open INC-\d+ details$/ });
  const href = await detailLink.getAttribute('href');
  expect(href).toContain('incident=INC-');
  const details = await context.newPage();
  await details.goto(href!);
  await expect(details.getByText('INCIDENT SAVED', { exact: true })).toBeVisible();
  await expect(details.locator('.quality-image')).toHaveAttribute('src', '/reference-images/door-hinge.png');
  await expect(details.getByText('Human confirmation: conversation', { exact: true })).toBeVisible();
  await expect(details.getByRole('heading', { name: 'Related measurement exceptions / 18' })).toBeVisible();
  await expect(details.getByText('not vehicle-specific camera footage', { exact: false }).first()).toBeVisible();
  await expect(details.getByRole('heading', { name: 'Recommended engineer checks' })).toBeVisible();
  await details.reload();
  await expect(details.getByRole('heading', { name: 'Approval & operation history' })).toBeVisible();
  await expect(station.getByRole('link', { name: 'Open incident details & evidence' })).toBeVisible({ timeout: 10000 });
  expect(await station.getByRole('link', { name: 'Open incident details & evidence' }).getAttribute('href')).toBe(href);
  const tower = await context.newPage();
  await tower.goto('/?workspace=quality&scoutTheme=dark');
  await expect(tower.getByText('DEMO-00428 / Station 42', { exact: true })).toBeVisible();
  await expect(tower.locator('.quality-history').getByRole('link', { name: 'DEMO-00427 / Station 42', exact: true })).toHaveAttribute('href', href!);
  await expect(details.getByText('No calibration, hold or production-release changes were authorized.', { exact: false })).toBeVisible();
  for (const workspace of [tower, station, details]) {
    await workspace.setViewportSize({ width: 390, height: 844 });
    expect(await workspace.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  await tower.screenshot({ path: 'test-results/proactive-control-tower.png', fullPage: true });
  expect(errors).toEqual([]);
});
